# v4 is a warm-started scale-lock fine-tune from the completed v3 checkpoint.
#
# Derived from the native-mode tensor audit of the exported v3 artifact:
# - residual prompt RMS scale-to-match SDXL: 0.56306547867397
# - residual pooled RMS scale-to-match SDXL: 0.3950532568952248
#
# We warm-start from the best v3 checkpoint, preserve its semantic direction,
# and apply those residual scale factors directly to the learned calibrator
# gains before training starts.
#
# Mean v3 gain -> derived v4 warm-start target mean gain:
# - prompt: 0.8305086493492126 * 0.56306547867397 = 0.467630750189
# - pooled: 1.038710117340088 * 0.3950532568952248 = 0.410345814825
export TARGET_OUTPUT_DIR="${TARGET_OUTPUT_DIR:-embedded_chunks/run-1m-2560}"
export QWEN_OUTPUT_DIR="${QWEN_OUTPUT_DIR:-embedded_chunks}"
