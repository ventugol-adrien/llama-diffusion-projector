export TRAIN_TIMING="${TRAIN_TIMING:-0}"
export TRAIN_MAX_STEPS="${TRAIN_MAX_STEPS:-0}"
export RUN_LABEL="${RUN_LABEL:-warm_v3_scale_lock_v4}"

export TRAIN_WARM_START_PATH="${TRAIN_WARM_START_PATH:-embedded_chunks/run-1m-2560/targets/sdxl/qwen_sdxl_projector_best_20260603_150916_full_mlp_calibrated_dnorm.pt}"
export TRAIN_WARM_START_STRICT="${TRAIN_WARM_START_STRICT:-1}"

export TRAIN_SDXL_PROJECTOR_ARCH="${TRAIN_SDXL_PROJECTOR_ARCH:-mlp}"
